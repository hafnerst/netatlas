// Embeds examples/*.yaml into src/generated/examples.ts so the single HTML
// file can offer them without reading any other file at runtime.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const order = ['enterprise-wan.yaml', 'datacenter-evpn.yaml', 'minimal.yaml', 'editor-new-network.yaml', 'minimal-edited.yaml', 'metro-ring.yaml', 'metro-ring-arranged.yaml'];
const files = readdirSync(join(root, 'examples'))
  .filter((f) => /\.ya?ml$/.test(f))
  .sort((a, b) => ((order.indexOf(a) + 1 || 99) - (order.indexOf(b) + 1 || 99)) || a.localeCompare(b));
const items = files.map((f) => ({ name: f, text: readFileSync(join(root, 'examples', f), 'utf8').replace(/\r\n/g, '\n') }));
const out =
  '// GENERATED by scripts/gen-examples.mjs from examples/*.yaml — do not edit.\n' +
  'export interface Example {\n  name: string;\n  text: string;\n}\n\n' +
  'export const EXAMPLES: Example[] = ' + JSON.stringify(items, null, 2) + ';\n';
const target = join(root, 'src', 'generated', 'examples.ts');
if (process.argv.includes('--check')) {
  // verify only: the committed file must equal what would be generated
  let cur = '';
  try {
    cur = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    /* missing */
  }
  if (cur !== out) {
    console.error('src/generated/examples.ts is out of date: run "npm run build" and commit the result');
    process.exit(1);
  }
  console.log(`src/generated/examples.ts is up to date (${items.length} examples)`);
} else {
  mkdirSync(join(root, 'src', 'generated'), { recursive: true });
  writeFileSync(target, out);
  console.log(`embedded ${items.length} examples: ${files.join(', ')}`);
}
