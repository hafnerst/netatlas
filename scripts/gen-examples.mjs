// Embeds the example models into generated modules, so the single HTML file
// can offer them without reading any other file at runtime.
//
//   examples/*.yaml       the PUBLIC examples: the File menu's catalog, in
//                         CATALOG order. src/generated/examples.ts (EXAMPLES)
//                         is part of dist/netatlas.html.
//   test/examples/*.yaml  the INTERNAL examples: test scenarios for features,
//                         edge cases, validation, layout and the simulation.
//   test/fixtures/*.yaml  generated test data (scripts/make-fixtures.mjs).
//                         Both go to src/generated/test-examples.ts
//                         (INTERNAL_EXAMPLES, FIXTURES), which only the test
//                         build (build/netatlas-test.html, entry app/main-test)
//                         imports: they are never shipped.
//
//   node scripts/gen-examples.mjs           write the modules
//   node scripts/gen-examples.mjs --check   verify that the committed modules are current
//
// Every file in examples/ must be in CATALOG and every entry of CATALOG must
// exist: a public example is a deliberate choice (docs: examples/README.md).
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
/** The public catalog, in the order of the File menu (the first is example 0 of a "#example=0" link). */
const CATALOG = ['enterprise-wan.yaml', 'enterprise-campus.yaml', 'datacenter-evpn.yaml', 'virtualization.yaml', 'private-house.yaml', 'dmz-services.yaml', 'hybrid-cloud.yaml', 'ot-network.yaml', 'timing-ptp.yaml', 'cross-domain.yaml'];

const yamls = (dir) => readdirSync(join(root, dir)).filter((f) => /\.ya?ml$/.test(f));
const read = (dir, f) => ({ name: f, text: readFileSync(join(root, dir, f), 'utf8').replace(/\r\n/g, '\n') });

const present = yamls('examples');
const unlisted = present.filter((f) => CATALOG.indexOf(f) < 0);
const missing = CATALOG.filter((f) => present.indexOf(f) < 0);
if (unlisted.length || missing.length) {
  if (unlisted.length) console.error(`examples/ has files that are not in the public catalog (scripts/gen-examples.mjs CATALOG): ${unlisted.join(', ')} — list them, or move them to test/examples/`);
  if (missing.length) console.error(`the public catalog lists files that examples/ doesn't have: ${missing.join(', ')}`);
  process.exit(1);
}
const items = CATALOG.map((f) => read('examples', f));
const internal = yamls(join('test', 'examples')).sort().map((f) => read(join('test', 'examples'), f));
const fixtures = yamls(join('test', 'fixtures')).sort().map((f) => read(join('test', 'fixtures'), f));
const clash = internal.filter((x) => CATALOG.indexOf(x.name) >= 0).map((x) => x.name);
if (clash.length) {
  console.error(`test/examples/ has files with the names of public examples: ${clash.join(', ')}`);
  process.exit(1);
}

const pub =
  '// GENERATED by scripts/gen-examples.mjs from examples/*.yaml — do not edit.\n' +
  'export interface Example {\n  name: string;\n  text: string;\n}\n\n' +
  '/** The public examples: the catalog of the File menu (shipped in dist/netatlas.html). */\n' +
  'export const EXAMPLES: Example[] = ' + JSON.stringify(items, null, 2) + ';\n';
const tst =
  '// GENERATED by scripts/gen-examples.mjs from test/examples/*.yaml and test/fixtures/*.yaml — do not edit.\n' +
  '// Imported only by the test build (src/app/main-test.ts): never part of dist/netatlas.html.\n' +
  "import { Example } from './examples';\n\n" +
  '/** The internal examples: test scenarios, loaded by name in the test build. */\n' +
  'export const INTERNAL_EXAMPLES: Example[] = ' + JSON.stringify(internal, null, 2) + ';\n\n' +
  '/** Generated test data for the in-browser self-test. */\n' +
  'export const FIXTURES: Example[] = ' + JSON.stringify(fixtures, null, 2) + ';\n';
const targets = [
  [join(root, 'src', 'generated', 'examples.ts'), pub],
  [join(root, 'src', 'generated', 'test-examples.ts'), tst],
];
if (process.argv.includes('--check')) {
  // verify only: the committed files must equal what would be generated
  let stale = false;
  for (const [file, out] of targets) {
    let cur = '';
    try {
      cur = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    } catch {
      /* missing */
    }
    if (cur !== out) {
      console.error(`${file} is out of date: run "npm run build" and commit the result`);
      stale = true;
    }
  }
  if (stale) process.exit(1);
  console.log(`src/generated/examples.ts and test-examples.ts are up to date (${items.length} public examples; ${internal.length} internal examples and ${fixtures.length} fixtures for the test build)`);
} else {
  mkdirSync(join(root, 'src', 'generated'), { recursive: true });
  for (const [file, out] of targets) writeFileSync(file, out);
  console.log(`embedded ${items.length} public examples: ${CATALOG.join(', ')}; for the test build ${internal.length} internal examples and ${fixtures.length} fixtures`);
}
