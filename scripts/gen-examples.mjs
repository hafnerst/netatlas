// Embeds examples/*.yaml into src/generated/examples.ts so the single HTML
// file can offer them without reading any other file at runtime. These are
// the examples of the File menu.
//
// test/fixtures/*.yaml is embedded next to them as FIXTURES: test data for
// the in-browser self-test only, never listed in the application.
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
// the order of the File menu
const order = ['enterprise-wan.yaml', 'datacenter-evpn.yaml', 'minimal.yaml', 'metro-ring.yaml', 'device-types.yaml', 'long-labels.yaml', 'addressing.yaml', 'port-bindings.yaml'];
const embed = (dir) =>
  readdirSync(join(root, dir))
    .filter((f) => /\.ya?ml$/.test(f))
    .sort((a, b) => ((order.indexOf(a) + 1 || 99) - (order.indexOf(b) + 1 || 99)) || a.localeCompare(b))
    .map((f) => ({ name: f, text: readFileSync(join(root, dir, f), 'utf8').replace(/\r\n/g, '\n') }));
const items = embed('examples');
const files = items.map((i) => i.name);
const fixtures = embed(join('test', 'fixtures'));
const out =
  '// GENERATED by scripts/gen-examples.mjs from examples/*.yaml and test/fixtures/*.yaml — do not edit.\n' +
  'export interface Example {\n  name: string;\n  text: string;\n}\n\n' +
  '/** The examples offered in the File menu. */\n' +
  'export const EXAMPLES: Example[] = ' + JSON.stringify(items, null, 2) + ';\n\n' +
  '/** Test data for the in-browser self-test; not offered in the application. */\n' +
  'export const FIXTURES: Example[] = ' + JSON.stringify(fixtures, null, 2) + ';\n';
const target = join(root, 'src', 'generated', 'examples.ts');
if (process.argv.includes('--check')) {
  // verify only: the committed file must equal what would be generated
  let cur = '';
  try {
    cur = readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
  } catch {
    /* missing */
  }
  if (cur !== out) {
    console.error('src/generated/examples.ts is out of date: run "npm run build" and commit the result');
    process.exit(1);
  }
  console.log(`src/generated/examples.ts is up to date (${items.length} examples, ${fixtures.length} fixtures)`);
} else {
  mkdirSync(join(root, 'src', 'generated'), { recursive: true });
  writeFileSync(target, out);
  console.log(`embedded ${items.length} examples: ${files.join(', ')} (and ${fixtures.length} self-test fixtures)`);
}
