// Writes docs/SUPPORT.md from the support catalog (src/model/support-catalog.ts,
// compiled to build/js): what each static analysis evaluates, and each
// protocol's, service's and application profile's support level, what it
// implements and what it leaves out. The same statements as the ⓘ notes and
// Help → User Manual → What NetAtlas models, written once.
//
//   node scripts/gen-support.mjs           write docs/SUPPORT.md (after tsc)
//   node scripts/gen-support.mjs --check   verify that it is current
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const js = join(root, 'build', 'js', 'model', 'support-catalog.js');
if (!existsSync(js)) {
  console.error('build/js/model/support-catalog.js not found: run tsc first (npm run build)');
  process.exit(1);
}
const { ANALYSIS_SUPPORT, supportCatalog, supportAreas } = require(js);
const { supportLabel } = require(join(root, 'build', 'js', 'model', 'support.js'));

const cell = (t) => String(t).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const lines = [
  '<!-- GENERATED by scripts/gen-support.mjs from src/model/support-catalog.ts — do not edit. -->',
  '# What NetAtlas models',
  '',
  'Each protocol, service and application profile states what NetAtlas does for',
  'it, at one of three levels: **Diagram only** (drawn and documented),',
  '**Configuration and validation** (its settings are checked; its exchanges are',
  'not simulated) and **Modeled behavior** (the simulation runs its exchanges and',
  'state, within the stated limits; never "full support"). The static analyses',
  'evaluate the configured model or a simulation snapshot and send nothing. The',
  'application shows the same statements in its ⓘ notes and in Help → User',
  'Manual → *What NetAtlas models*. [LIMITATIONS.md](LIMITATIONS.md) adds the',
  'simplifications that cut across them.',
  '',
  '## Static analysis (Analyze)',
  '',
  '| Analysis | Evaluates | Does not establish |',
  '| --- | --- | --- |',
  ...ANALYSIS_SUPPORT.map((a) => `| ${cell(a.name)} | ${cell(a.does)} | ${cell(a.not)} |`),
];
const cat = supportCatalog();
for (const area of supportAreas()) {
  lines.push('', `## ${area}`, '', '| Name | Level | Implemented | Not modeled |', '| --- | --- | --- | --- |');
  for (const e of cat.filter((x) => x.area === area)) lines.push(`| ${cell(e.name)} | ${supportLabel(e.support.level)} | ${cell(e.support.does)} | ${cell(e.support.not)} |`);
}
const out = lines.join('\n') + '\n';
const file = join(root, 'docs', 'SUPPORT.md');
if (process.argv.includes('--check')) {
  const cur = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
  if (cur !== out) {
    console.error('docs/SUPPORT.md is not current: run "node scripts/gen-support.mjs" (after tsc)');
    process.exit(1);
  }
  console.log('docs/SUPPORT.md is up to date (' + cat.length + ' entries, ' + ANALYSIS_SUPPORT.length + ' analyses)');
} else {
  writeFileSync(file, out);
  console.log('wrote docs/SUPPORT.md (' + cat.length + ' entries, ' + ANALYSIS_SUPPORT.length + ' analyses)');
}
