// The capability matrix and the service matrix of docs/FORMAT.md, from the resolver
// (src/model/capabilities.ts) and the service registry (src/model/service-registry.ts):
//
//   node scripts/capability-matrix.mjs          print them
//   node scripts/capability-matrix.mjs --write  write them between their markers in docs/FORMAT.md
//
// test/device-model-doc.test.mjs and test/services.test.mjs check that the document and the code agree.
// Run after "npm run build".
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const Cap = require(join(root, 'build', 'js', 'model', 'capabilities.js'));
const DT = require(join(root, 'build', 'js', 'model', 'device-types.js'));
const Reg = require(join(root, 'build', 'js', 'model', 'service-registry.js'));

export const BEGIN = '<!-- capability-matrix:begin (generated by scripts/capability-matrix.mjs) -->';
export const END = '<!-- capability-matrix:end -->';
export const SVC_BEGIN = '<!-- service-matrix:begin (generated by scripts/capability-matrix.mjs) -->';
export const SVC_END = '<!-- service-matrix:end -->';

/** The rows: each type in its default form, then each other mode, Supports Layer 3, implementation and purpose. */
function rows() {
  const out = [];
  for (const t of DT.DEVICE_TYPES) {
    const modes = DT.modesOf(t.id);
    if (t.id === 'system') {
      for (const p of DT.SYSTEM_PURPOSES) out.push([`${t.label} · ${p.label}`, { type: t.id, purpose: p.id }]);
      continue;
    }
    if (t.id === 'security_gateway') {
      out.push([`${t.label} (no implementation yet)`, { type: t.id }]);
      for (const i of ['filtering_bridge', 'filtering_router', 'protocol_break']) out.push([`${t.label} · ${i.replace(/_/g, ' ')}`, { type: t.id, separation: { implementation: i } }]);
      continue;
    }
    out.push([modes.length ? `${t.label} · ${modes[0].label}` : t.label, { type: t.id }]);
    for (const m of modes.slice(1)) out.push([`${t.label} · ${m.label}`, { type: t.id, mode: m.id }]);
    if (Cap.layer3Option(t.id)) out.push([`${t.label} · Supports Layer 3`, { type: t.id, layer3: true }]);
  }
  return out;
}

const COLS = [
  ['host', (c) => c.host],
  ['L2 forward', (c) => c.l2Forward],
  ['L3 forward', (c) => c.l3Forward],
  ['policy', (c) => c.policy],
  ['inline (pairs)', (c) => c.inline],
  ['passive copy', (c) => c.passiveCopy],
  ['pass-through', (c) => c.passThrough],
  ['external transit', (c) => c.externalTransit],
  ['hosts guests', (c) => (c.canHostGuests.vms ? 'VMs' : '') + (c.canHostGuests.vms && c.canHostGuests.containers ? ', ' : '') + (c.canHostGuests.containers ? 'containers' : '')],
  ['is a guest', (c) => c.canBeGuest || ''],
  ['VPN', (c) => (c.vpnOnlyTransit ? 'terminates; only via its VPN' : c.vpnTermination ? 'terminates' : '')],
  ['separation', (c) => (c.separation ? c.separation.replace(/_/g, ' ') : c.securityGateway ? 'none yet' : '')],
  ['session break', (c) => c.sessionBreak],
  ['routing protocols', (c) => c.routingProtocols],
  ['management ifaces', (c) => c.managementInterfaces],
];

export function matrix() {
  const head = `| Device | ${COLS.map((c) => c[0]).join(' | ')} |`;
  const sep = `|---|${COLS.map(() => ':-:').join('|')}|`;
  const cell = (v) => (v === true ? '✓' : v === false || v === '' || v === null || v === undefined ? '' : String(v));
  const body = rows().map(([label, d]) => {
    const c = Cap.capabilities(d);
    return `| ${label} | ${COLS.map(([, f]) => cell(f(c))).join(' | ')} |`;
  });
  return [head, sep, ...body].join('\n');
}

/** The service matrix: each service, its key and badge, where it is built in, where it is optional, and the conditions on top. */
export function serviceMatrixMd() {
  const label = (t) => DT.deviceTypeLabel(t) || t;
  // the variants a condition may rule out: a Layer 2 switch, a transparent firewall, a System that is not a host
  const variants = [{ type: 'switch' }, { type: 'firewall', mode: 'transparent' }, { type: 'system', purpose: 'pass_through' }, { type: 'server' }];
  const out = Reg.SERVICES.map((s) => {
    const conds = [];
    for (const v of variants) {
      if (s.types.indexOf(v.type) < 0) continue;
      const why = Reg.serviceEligibility(s, v);
      if (why && conds.indexOf(why) < 0) conds.push(why);
    }
    const built = (s.builtIn || []).map(label).join(', ');
    const opt = s.types.filter((t) => (s.builtIn || []).indexOf(t) < 0).map(label).join(', ');
    return `| ${s.label} | \`${s.id}\` | ${s.badge} | ${built ? built + (s.required ? ' (its configuration required)' : '') : ''} | ${opt} | ${conds.join('; ')} |`;
  });
  return ['| Service | Key | Badge | Built into | Optional on | Conditions |', '|---|---|---|---|---|---|', ...out].join('\n');
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const m = matrix();
  if (process.argv.includes('--write')) {
    const p = join(root, 'docs', 'FORMAT.md');
    let s = readFileSync(p, 'utf8');
    for (const [b, e, body, what] of [
      [BEGIN, END, m, 'capability'],
      [SVC_BEGIN, SVC_END, serviceMatrixMd(), 'service'],
    ]) {
      const i = s.indexOf(b);
      const j = s.indexOf(e);
      if (i < 0 || j < i) throw new Error(`docs/FORMAT.md has no ${what} matrix markers`);
      s = s.slice(0, i + b.length) + '\n' + body + '\n' + s.slice(j);
    }
    writeFileSync(p, s);
    console.log('wrote the capability and the service matrix into docs/FORMAT.md');
  } else console.log(m + '\n\n' + serviceMatrixMd());
}
